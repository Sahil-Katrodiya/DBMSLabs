--11. Create INSTEAD OF INSERT trigger to prevent insertion of students whose SPI is greater than 10 or less 
--than 0. 
CREATE TRIGGER TRG_SPI
ON STUDENT
INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS(
        SELECT *
        FROM INSERTED
        WHERE SPI > 10 OR SPI < 0)
        PRINT 'INVALID SPI';
    ELSE
        INSERT INTO STUDENT
        SELECT * FROM STUDENT;
END;
DROP TRIGGER TRG_SPI

