--5. Create trigger for preventing duplicate employee records having same FIRSTNAME, LASTNAME, and CITY. 
CREATE TRIGGER TRG_DUPLICATE
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS(
        SELECT *
        FROM EMPLOYEE E
        JOIN INSERTED I
        ON E.EID = I.EID)
        PRINT 'DUPLICATE RECORD NOT ALLOWED';
    ELSE
        INSERT INTO EMPLOYEE
        SELECT * FROM EMPLOYEE;
END;
DROP TRIGGER TRG_DUPLICATE

 
